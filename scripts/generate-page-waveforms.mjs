/**
 * Generate compact waveform peaks for every audio player on the project page.
 * Usage: node scripts/generate-page-waveforms.mjs
 */

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PEAK_COUNT = 320;
const ANALYSIS_SAMPLE_RATE = 8000;
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const repositoryRoot = resolve(scriptDirectory, '..');
const indexPath = join(repositoryRoot, 'index.html');
const outputPath = join(repositoryRoot, 'assets', 'js', 'waveform-peaks.js');

/** @param {string} source */
function normalizeSource(source) {
  return source.split(/[?#]/, 1)[0];
}

/** @param {string} filePath @returns {Float32Array} */
function decodeMonoAudio(filePath) {
  const buffer = execFileSync(
    'ffmpeg',
    [
      '-v', 'error', '-i', filePath, '-vn', '-ac', '1', '-ar', String(ANALYSIS_SAMPLE_RATE),
      '-f', 'f32le', 'pipe:1',
    ],
    { encoding: 'buffer', maxBuffer: 64 * 1024 * 1024 },
  );
  return new Float32Array(buffer.buffer, buffer.byteOffset, Math.floor(buffer.byteLength / 4));
}

/** @param {Float32Array} samples @returns {number[]} */
function buildPeaks(samples) {
  const rawLevels = Array.from({ length: PEAK_COUNT }, (_, peakIndex) => {
    const start = Math.floor((peakIndex * samples.length) / PEAK_COUNT);
    const end = Math.max(start + 1, Math.floor(((peakIndex + 1) * samples.length) / PEAK_COUNT));
    let peak = 0;
    let squareSum = 0;
    for (let sampleIndex = start; sampleIndex < Math.min(end, samples.length); sampleIndex += 1) {
      const amplitude = Math.abs(samples[sampleIndex]);
      peak = Math.max(peak, amplitude);
      squareSum += amplitude * amplitude;
    }
    const measuredSamples = Math.max(1, Math.min(end, samples.length) - start);
    const rms = Math.sqrt(squareSum / measuredSamples);
    return (0.65 * peak) + (0.35 * rms);
  });
  const maximumLevel = Math.max(...rawLevels);
  if (maximumLevel <= 0) return rawLevels;
  return rawLevels.map((level) => Number(Math.pow(level / maximumLevel, 0.72).toFixed(3)));
}

const html = readFileSync(indexPath, 'utf8');
const sources = [...html.matchAll(/<audio\b[^>]*\bsrc="([^"]+)"/g)]
  .map((match) => normalizeSource(match[1]))
  .filter((source, index, values) => values.indexOf(source) === index)
  .sort();

if (sources.length === 0) throw new Error(`No audio sources found in ${indexPath}`);

const waveformPeaks = Object.fromEntries(sources.map((source) => [
  source,
  buildPeaks(decodeMonoAudio(join(repositoryRoot, source))),
]));

writeFileSync(
  outputPath,
  `/* Generated by scripts/generate-page-waveforms.mjs. */\nwindow.PAGE_WAVEFORM_PEAKS=${JSON.stringify(waveformPeaks)};\n`,
);
